export const messages = { en, es };
export let locale = "en";
export const t = (key) => messages[locale][key] ?? messages.en[key] ?? key;
/** A string or a function of arguments, by key (and optional nested key). */
export const tf = (key, ...args) => {
  const value = t(key);
  return typeof value === "function" ? value(...args) : value;
};
export const nested = (group, key, ...args) => {
  const value = messages[locale][group]?.[key] ?? messages.en[group]?.[key];
  if (value === undefined) return key;
  return typeof value === "function" ? value(...args) : value;
};
export const errorText = (code) =>
  messages[locale].errors[code] ??
  messages.en.errors[code] ??
  messages[locale].errors.operation_failed;
export function setLocale(value) {
  locale = String(value ?? "")
    .toLowerCase()
    .startsWith("es")
    ? "es"
    : "en";
  document.documentElement.lang = locale;
  document.title = messages[locale].appName;
}
