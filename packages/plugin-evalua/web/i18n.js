export const messages = { en, es };
export let locale = "en";
export const t = (key) => messages[locale][key] ?? messages.en[key] ?? key;
/** A string or a sentence built from arguments. */
export const tf = (key, ...args) => {
  const value = t(key);
  return typeof value === "function" ? value(...args) : value;
};
export const errorText = (code) =>
  messages[locale].errors[code] ??
  messages.en.errors[code] ??
  messages[locale].errors.operation_failed;
/** The label of an exercise family in the UI language; the id only as a last resort. */
export const familyLabel = (id) => FAMILY_LABELS[id]?.[locale] ?? FAMILY_LABELS[id]?.en ?? id;
/** A knowledge-base name ({ es, en? }) in the UI language, falling back to Spanish. */
export const localName = (name) =>
  (name && (name[locale] ?? name.es ?? Object.values(name)[0])) || "";
/** `es-CO` -> "es"; `en`, `fr` or anything else -> "en". */
export const pickLocale = (value) =>
  String(value ?? "")
    .toLowerCase()
    .startsWith("es")
    ? "es"
    : "en";
export function setLocale(value) {
  locale = pickLocale(value);
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
    document.title = messages[locale].appName;
  }
}
