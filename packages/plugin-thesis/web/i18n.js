export const messages = { en, es };
export let locale = "en";

/** `es*` → Spanish, anything else → English. */
export const resolveLocale = (value) =>
  String(value ?? "")
    .toLowerCase()
    .startsWith("es")
    ? "es"
    : "en";

/** A string (or nested group) by dotted key, English as the fallback. */
export function t(key) {
  // Keys may contain dots themselves ("nextLabels.project.init"): try the longest rest first.
  const pick = (dict) => {
    const parts = key.split(".");
    let node = dict;
    for (let i = 0; i < parts.length && node && typeof node === "object"; i++) {
      const rest = parts.slice(i).join(".");
      if (node[rest] !== undefined) return node[rest];
      node = node[parts[i]];
    }
    return undefined;
  };
  return pick(messages[locale]) ?? pick(messages.en) ?? key;
}

/** A string by key, calling it with `args` when it is a function. */
export function tf(key, ...args) {
  const value = t(key);
  return typeof value === "function" ? value(...args) : value;
}

export const errorText = (code) =>
  messages[locale].errors[code] ??
  messages.en.errors[code] ??
  messages[locale].errors.operation_failed;

export function setLocale(value) {
  locale = resolveLocale(value);
  if (globalThis.document) {
    document.documentElement.lang = locale;
    document.title = messages[locale].appName;
  }
}
